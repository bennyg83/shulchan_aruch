function applyPhraseMap(text) {
  let t = text;
  const sorted = [...PHRASE].sort((a, b) => b[0].length - a[0].length);
  for (const [he, en] of sorted) {
    if (!he) continue;
    t = t.split(he).join(en);
  }
  return t;
}

/** Extract bold label from HTML */
function extractLabel(hebrew) {
  const m = hebrew.match(/<b>(.*?)<\/b>/i);
  if (!m) return "";
  return stripHtml(m[1]).trim();
}

