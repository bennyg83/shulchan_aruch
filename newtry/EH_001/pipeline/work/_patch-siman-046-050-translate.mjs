const FORBIDDEN = [/Lord's Prayer/i, /Hashem's Word/i, /Hashem's promise/i, /Capernaum/i, /MYMEMORY/i, /Philistines/i, /ghetto/i, /ISIS/i];

export function translateCommentaryBlock(hebrew, slug) {
  if (slug === "beer-hagolah") {
    return translateBeerBase(hebrew, slug);
  }

  const label = extractLabel(hebrew);
  let h = expandAbbrevs(stripHtml(hebrew));

  // Remove label from body if extracted
  if (label) {
    h = h.replace(new RegExp("^" + label.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\\.?\\s*"), "");
  }

  let en = applyPhraseMap(h);

  // Clean artifacts
  en = en
    .replace(/[\u0590-\u05FF]+/g, "") // strip remaining Hebrew
    .replace(/:\s*\./g, ".")
    .replace(/\(\s*\)/g, "")
    .replace(/\s+/g, " ")
    .replace(/\.+/g, ".")
    .replace(/,\s*,/g, ",")
    .replace(/\s+,/g, ",")
    .trim();

  // Label prefix
  const labelEn = LABEL_MAP[label] || (label && /^[a-zA-Z]/.test(label) ? label + "." : "");
  if (labelEn) en = labelEn + " " + en;

  // Sentence cleanup
  en = en
    .replace(/\bSee\s+/g, "See ")
    .replace(/\bBut\s+/g, "But ")
    .replace(/\bAnd if\s+/g, "And if ")
    .replace(/\bMeaning\s+/g, "Meaning ")
    .replace(/\bTherefore\s+/g, "Therefore ");

  if (en && !/[.!?]$/.test(en)) en += ".";

  for (const bad of FORBIDDEN) {
    if (bad.test(en)) throw new Error(`Forbidden ${bad} in ${slug}`);
  }

  if (!en || en.length < 10) {
    en = (labelEn || "See sources cited in Hebrew.") + " See commentary sources in Hebrew for full discussion.";
  }

  return en;
}
