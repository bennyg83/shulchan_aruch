import { StrictMode } from "react";
import { createRoot } from "react-dom/client";
import App from "./App.jsx";
import ErrorBoundary from "./lib/ErrorBoundary.jsx";
import "./web.css";

/**
 * Drop legacy runtime caches (CacheFirst "corpus-bundles") that can pin
 * stale siman JSON for up to a year across SW updates.
 */
async function clearLegacyCorpusCaches() {
  if (!("caches" in window)) return false;
  try {
    const keys = await caches.keys();
    const stale = keys.filter(
      (k) =>
        k === "corpus-bundles" ||
        k === "corpus-catalog" ||
        /(^|-)corpus-bundles$/.test(k) ||
        /(^|-)corpus-catalog$/.test(k)
    );
    if (!stale.length) return false;
    await Promise.all(stale.map((k) => caches.delete(k)));
    return true;
  } catch {
    return false;
  }
}

// Register the Workbox service worker (generated by vite-plugin-pwa).
// Standalone native builds (Capacitor / WebView APK) bundle corpus in assets — no SW.
if (typeof window !== "undefined" && !import.meta.env.VITE_STANDALONE) {
  let refreshing = false;
  if ("serviceWorker" in navigator) {
    navigator.serviceWorker.addEventListener("controllerchange", () => {
      if (refreshing) return;
      refreshing = true;
      window.location.reload();
    });
  }

  import("virtual:pwa-register")
    .then(async ({ registerSW }) => {
      const cleared = await clearLegacyCorpusCaches();
      if (cleared && !sessionStorage.getItem("corpus-cache-cleared-v3")) {
        sessionStorage.setItem("corpus-cache-cleared-v3", "1");
        window.location.reload();
        return;
      }

      const updateSW = registerSW({
        immediate: true,
        onOfflineReady() {
          window.dispatchEvent(new CustomEvent("pwa-offline-ready"));
        },
        onNeedRefresh() {
          // autoUpdate + skipWaiting: apply new SW (triggers controllerchange → reload).
          updateSW?.(true);
        },
        onRegisteredSW(_swUrl, registration) {
          if (!registration) return;
          const check = () => registration.update().catch(() => {});
          // Pick up corpus/app deploys without requiring a hard refresh.
          document.addEventListener("visibilitychange", () => {
            if (document.visibilityState === "visible") check();
          });
          window.addEventListener("focus", check);
          setInterval(check, 60 * 60 * 1000);
          if (registration.installing) {
            window.dispatchEvent(new CustomEvent("pwa-installing"));
            registration.installing.addEventListener("statechange", (e) => {
              if (e.target.state === "installed") {
                window.dispatchEvent(new CustomEvent("pwa-offline-ready"));
              }
            });
          }
        },
        onRegisterError(error) {
          console.warn("PWA service worker registration failed:", error);
        },
      });
    })
    .catch(() => {
      // virtual:pwa-register only exists in a Vite PWA build — ignore in dev/test.
    });
}

function showBootError(rootEl, err) {
  const msg = err?.message || String(err);
  rootEl.innerHTML =
    `<div style="margin:2rem;font-family:Georgia,serif;max-width:40rem">` +
    `<p style="color:#a63d3d;font-weight:700">React failed to start</p>` +
    `<pre style="white-space:pre-wrap;font-size:13px">${msg.replace(/</g, "&lt;")}</pre></div>`;
  console.error("[oc-web-reader]", err);
}

const rootEl = document.getElementById("root");
if (!rootEl) {
  document.body.innerHTML = "<p style='margin:2rem'>Missing #root element.</p>";
} else {
  try {
    createRoot(rootEl).render(
      <StrictMode>
        <ErrorBoundary>
          <App />
        </ErrorBoundary>
      </StrictMode>
    );
  } catch (err) {
    showBootError(rootEl, err);
  }
}
