export function isBadMt447(en) {
  if (!en || !en.trim()) return true;
  if (en.length < 8 && /^[\(\)\d\s\-–—.:,'"]+$/.test(en)) return true;
  const plain = plainFromHtml(en);
  if (countHebrewChars(plain) >= 4) return true;
  return BAD_MT_447.some((re) => re.test(en));
}
