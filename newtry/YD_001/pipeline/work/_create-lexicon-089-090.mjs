function extractRepsFromSource(filePath) {
  const text = fs.readFileSync(filePath, 'utf8');
  const map = {};
  const re =
    /\[\s*\/((?:\\.|[^/])+)\/[gimsuy]*\s*,\s*'((?:\\.|[^'])*)'\s*\]/g;
  let m;
  while ((m = re.exec(text))) {
    let pat = m[1];
    let en = m[2];
    pat = pat.replace(/\\(.)/g, '$1');
    en = en.replace(/\\(.)/g, '$1');
    if (pat.startsWith('^') || pat.endsWith('$') || /[+*?[\]()]/.test(pat.replace(/\\./g, '')))
      continue;
    const he = pat.replace(/\s+/g, ' ').trim();
    if (/^[\u0590-\u05FF"'״׳\s]+$/.test(he) && he.length >= 1) map[he] = en;
  }
  return map;
}

