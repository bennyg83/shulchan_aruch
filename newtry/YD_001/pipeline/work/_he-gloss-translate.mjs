export function translateGloss(he) {
  let raw = stripHe(he);
  // Citation-only short lines
  if (/^[A-Za-z\u0590-\u05FF\s":'.,\-–—\(\)\[\]״׳]+:$/.test(raw) && raw.length < 120 && !/כתב/.test(raw)) {
    return translateCitation(raw);
  }
  let t = raw;
  for (const [re, rep] of WRITERS) t = t.replace(re, rep);
  // Bold heading: first word before period often a label
  t = t.replace(/^([^\.\s]+)\.\s*/, (m, w) => {
    const label = translateWord(w);
    return label ? `${label}. ` : m;
  });
  // Cleanup leftover Hebrew punctuation artifacts
  t = t.replace(/\s+/g, ' ').trim();
  return t;
}

